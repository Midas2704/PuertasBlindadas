-- INT-03: soporte aditivo para operaciones físicas idempotentes y reservas localizadas.
-- No modifica registros históricos ni concede permisos M4.

ALTER TABLE "inventario"."reserva_inventario"
  ADD COLUMN "bodega_id_bodega" BIGINT,
  ADD COLUMN "lote_id_lote" BIGINT;

ALTER TABLE "inventario"."reserva_inventario"
  ADD CONSTRAINT "fk_reserva_inventario_bodega"
    FOREIGN KEY ("bodega_id_bodega") REFERENCES "inventario"."bodega"("bodega_id_bodega")
    ON DELETE RESTRICT ON UPDATE NO ACTION,
  ADD CONSTRAINT "fk_reserva_inventario_lote"
    FOREIGN KEY ("lote_id_lote") REFERENCES "inventario"."lote"("lote_id_lote")
    ON DELETE RESTRICT ON UPDATE NO ACTION,
  ADD CONSTRAINT "chk_reserva_inventario_ubicacion_completa"
    CHECK (("bodega_id_bodega" IS NULL AND "lote_id_lote" IS NULL)
        OR ("bodega_id_bodega" IS NOT NULL AND "lote_id_lote" IS NOT NULL));

CREATE INDEX "idx_reserva_inventario_ubicacion_estado"
  ON "inventario"."reserva_inventario"("material_sku", "bodega_id_bodega", "lote_id_lote", "reserva_inventario_estado_reserva");

CREATE TABLE "inventario"."operacion_inventario" (
  "operacion_inventario_id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "clave_idempotencia" VARCHAR(160) NOT NULL,
  "tipo_operacion" VARCHAR(20) NOT NULL,
  "hash_solicitud" CHAR(64) NOT NULL,
  "actor_id" BIGINT NOT NULL,
  "material_sku" VARCHAR(16) NOT NULL,
  "bodega_id_bodega" BIGINT NOT NULL,
  "lote_id_lote" BIGINT NOT NULL,
  "movimiento_inventario_id" BIGINT,
  "reserva_inventario_id" BIGINT,
  "resultado" JSONB NOT NULL,
  "creado_en" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "confirmado_en" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "pk_operacion_inventario" PRIMARY KEY ("operacion_inventario_id"),
  CONSTRAINT "uq_operacion_inventario_clave" UNIQUE ("clave_idempotencia"),
  CONSTRAINT "uq_operacion_inventario_movimiento" UNIQUE ("movimiento_inventario_id"),
  CONSTRAINT "chk_operacion_inventario_tipo" CHECK ("tipo_operacion" IN ('ENTRADA','SALIDA','RESERVA','LIBERACION','AJUSTE')),
  CONSTRAINT "fk_operacion_inventario_actor" FOREIGN KEY ("actor_id") REFERENCES "comun"."usuario"("usuario_id_usuario") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "fk_operacion_inventario_material" FOREIGN KEY ("material_sku") REFERENCES "inventario"."material"("material_sku") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "fk_operacion_inventario_bodega" FOREIGN KEY ("bodega_id_bodega") REFERENCES "inventario"."bodega"("bodega_id_bodega") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "fk_operacion_inventario_lote" FOREIGN KEY ("lote_id_lote") REFERENCES "inventario"."lote"("lote_id_lote") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "fk_operacion_inventario_movimiento" FOREIGN KEY ("movimiento_inventario_id") REFERENCES "inventario"."movimiento_inventario"("movimiento_inventario_id_movimiento") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "fk_operacion_inventario_reserva" FOREIGN KEY ("reserva_inventario_id") REFERENCES "inventario"."reserva_inventario"("reserva_inventario_id_reserva") ON DELETE RESTRICT ON UPDATE NO ACTION
);

CREATE INDEX "idx_operacion_inventario_actor_fecha"
  ON "inventario"."operacion_inventario"("actor_id", "creado_en" DESC);

COMMENT ON TABLE "inventario"."operacion_inventario" IS
  'Ledger idempotente de INT-03. Conserva una única confirmación por operación de negocio.';
COMMENT ON COLUMN "inventario"."reserva_inventario"."bodega_id_bodega" IS
  'Ubicación acreditada para reservas nuevas; NULL conserva compatibilidad histórica.';
